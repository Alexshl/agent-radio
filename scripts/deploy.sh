#!/usr/bin/env bash
# Release gate of agent-radio:  worktree -> staging -> prod.
#
#   scripts/deploy.sh staging                 build THIS checkout into the staging stack, run the acceptance test, stamp the commit on PASS
#   scripts/deploy.sh prod [options]          the production deploy (only from the main checkout, only a commit that passed staging)
#   scripts/deploy.sh rollback                prod: put the previous app image back
#
# prod options:
#   --allow-listener-drop   needed when a service that carries the stream (front, icecast, liquidsoap) has to restart: listeners are cut once
#   --smoke-say             also send a spoken message at the end (needs AGENT_RADIO_URL / AGENT_RADIO_KEY, see client/agent-radio)
#   --dry-run               print the plan and stop (changes nothing)
#
# Two stacks, never mixed: staging = compose project `agent-radio-staging` (volumes agent-radio-staging_*, port 127.0.0.1:8796, .env.staging),
# prod = project `agent-radio` (port 8790, .env). Each mode only ever talks to its own project.
# Shared state lives in <main checkout>/.deploy/ (git-ignored): staging pass stamps, the staging API key, what prod runs.
set -euo pipefail

HERE=$(cd "$(dirname "$0")/.." && pwd)
MAIN=$(dirname "$(git -C "$HERE" rev-parse --path-format=absolute --git-common-dir)")
STATE="$MAIN/.deploy"
MODE=${1:-}
[ $# -gt 0 ] && shift

say() { printf '%s\n' "$*"; }
die() { printf 'deploy: %s\n' "$*" >&2; exit 1; }
banner() { printf '\n########################################################################\n# %s\n########################################################################\n\n' "$*"; }

[ -z "$MODE" ] && die 'usage: scripts/deploy.sh staging | prod [--allow-listener-drop] [--smoke-say] [--dry-run] | rollback'
mkdir -p "$STATE"

SHA=$(git -C "$HERE" rev-parse HEAD)
dirty() { [ -n "$(git -C "$HERE" status --porcelain)" ]; }

case "$MODE" in
  staging)
    PROJECT=agent-radio-staging
    ENV_FILE="$MAIN/.env.staging"
    PORT=8796
    ;;
  prod | rollback)
    PROJECT=agent-radio
    ENV_FILE="$MAIN/.env"
    PORT=$(sed -n 's/^PORT=//p' "$ENV_FILE" 2>/dev/null | tail -n 1)
    PORT=${PORT:-8790}
    ;;
  *) die "unknown mode: $MODE" ;;
esac

# every compose call of this script goes through here: one project, one env file, one compose file
dc() { docker compose -p "$PROJECT" --env-file "$ENV_FILE" -f "$HERE/compose.yaml" "$@"; }

# the app container talks to its own stack only: run a node snippet inside it
app_node() { dc exec -T app node --input-type=module -e "$1"; }

wait_http() { # <url> <seconds> <label>
  local end=$((SECONDS + $2))
  until curl -fsS -m 3 -o /dev/null "$1" 2>/dev/null; do
    [ $SECONDS -ge $end ] && die "$3 did not become healthy within $2 s ($1)"
    sleep 2
  done
}

wait_healthy() { # app + front + engine stations all in place
  say "waiting for the stack to be healthy ..."
  wait_http "http://127.0.0.1:$PORT/__front/healthz" 120 'the front'
  wait_http "http://127.0.0.1:$PORT/healthz" 180 'the app'
  local end=$((SECONDS + 120))
  until app_node "const r = await fetch('http://127.0.0.1:' + (process.env.PORT ?? 8790) + '/internal/health'); process.exit(r.ok ? 0 : 1)" 2>/dev/null; do
    [ $SECONDS -ge $end ] && die 'the engine did not get all stations within 120 s'
    sleep 2
  done
  say "healthy."
}

stream_url() { # a listen URL of the first station, read from the stack's own database
  app_node "
import Database from 'better-sqlite3'
const db = new Database((process.env.DATA_DIR ?? '/data') + '/radio.db', { readonly: true })
const s = db.prepare('select id, listen_token as t from stations limit 1').get()
if (s) console.log('http://127.0.0.1:${PORT}/stream/' + s.id + '.mp3?k=' + s.t)
"
}

# ------------------------------------------------------------------------------------------------ staging
staging_env() {
  [ -f "$ENV_FILE" ] && return
  say "creating $ENV_FILE (random secrets, local only) ..."
  local music="$STATE/staging-music"
  mkdir -p "$music"
  umask 077
  cat >"$ENV_FILE" <<EOF
# Permanent staging stack of agent-radio (generated by scripts/deploy.sh staging). Never used by production.
COMPOSE_PROJECT_NAME=agent-radio-staging
BIND_ADDR=127.0.0.1
PORT=$PORT
PUBLIC_URL=http://127.0.0.1:$PORT
ADMIN_EMAIL=staging-admin@example.test
ADMIN_PASSWORD=$(openssl rand -hex 12)
APP_SECRET=$(openssl rand -hex 24)
ICECAST_SOURCE_PASSWORD=$(openssl rand -hex 12)
ICECAST_ADMIN_PASSWORD=$(openssl rand -hex 12)
MUSIC_DIR=$music
TTS_PROVIDER=piper
TTS_VOICE=uk_UA-mykyta-high
TTS_LANG=uk
# the heavy local-voices sidecar stays off here (RAM)
COMPOSE_PROFILES=
EOF
  chmod 600 "$ENV_FILE"
}

staging_music() {
  local music
  music=$(sed -n 's/^MUSIC_DIR=//p' "$ENV_FILE")
  [ -n "$music" ] || die "MUSIC_DIR missing in $ENV_FILE"
  [ "$music" != "$(sed -n 's/^MUSIC_DIR=//p' "$MAIN/.env" 2>/dev/null || true)" ] || die 'staging MUSIC_DIR is the production one'
  mkdir -p "$music/sample"
  "$HERE/scripts/staging-sample-music.sh" "$music/sample"
  chmod -R a+rwX "$music" 2>/dev/null || true
}

staging_key() { # the API key of the staging admin (created once, kept in .deploy)
  local keyfile="$STATE/staging-api-key"
  if [ -s "$keyfile" ] && AGENT_RADIO_URL="http://127.0.0.1:$PORT" AGENT_RADIO_KEY=$(cat "$keyfile") "$HERE/client/agent-radio" status 2>/dev/null | grep -q '^agent-radio: online'; then
    return
  fi
  say "creating the staging API key ..."
  (umask 077; dc exec -T app node --import tsx src/server/cli.ts create-key staging-admin@example.test acceptance | tail -n 1 >"$keyfile")
  [ -s "$keyfile" ] || die 'could not create the staging API key'
}

deploy_staging() {
  [ "$PROJECT" = agent-radio-staging ] || die 'internal: wrong project for staging'
  banner "STAGING  $(git -C "$HERE" rev-parse --short HEAD)  ($HERE)"
  staging_env
  staging_music
  dc config --quiet
  dc up -d --build --remove-orphans
  # bind-mounted config files do not change a container's compose hash: apply them the way prod does (liquidsoap restart, graceful caddy reload)
  local liq_now caddy_now
  liq_now=$(file_hash "$HERE/liquidsoap/radio.liq")
  caddy_now=$(file_hash "$HERE/deploy/Caddyfile")
  if [ "$liq_now" != "$(sed -n 's/^liquidsoap=//p' "$STATE/staging-state" 2>/dev/null | tail -n 1)" ]; then
    say 'radio.liq changed since the last staging deploy: restarting liquidsoap'
    dc restart liquidsoap
  fi
  if [ "$caddy_now" != "$(sed -n 's/^caddyfile=//p' "$STATE/staging-state" 2>/dev/null | tail -n 1)" ]; then
    dc exec -T front caddy reload --config /etc/caddy/Caddyfile >/dev/null 2>&1 || true
  fi
  printf 'liquidsoap=%s\ncaddyfile=%s\n' "$liq_now" "$caddy_now" >"$STATE/staging-state"
  wait_healthy
  staging_key
  # a station with some music (silence otherwise), best effort
  curl -fsS -m 10 -X PUT -H "Authorization: Bearer $(cat "$STATE/staging-api-key")" -H 'Content-Type: application/json' \
    -d '{"type":"playlist","dir":"sample"}' "http://127.0.0.1:$PORT/api/station/source" >/dev/null 2>&1 || say '(sample playlist not set; the station plays silence)'

  local log="$STATE/acceptance-$(git -C "$HERE" rev-parse --short HEAD).log"
  say "running the acceptance test (log: $log) ..."
  set +e
  ACCEPT_COMPOSE="docker compose -p $PROJECT --env-file $ENV_FILE -f $HERE/compose.yaml" ACCEPT_PROJECT=$PROJECT \
    "$HERE/scripts/acceptance.sh" "http://127.0.0.1:$PORT" "$(cat "$STATE/staging-api-key")" 2>&1 | tee "$log"
  local rc=${PIPESTATUS[0]}
  set -e
  if [ "$rc" -ne 0 ]; then
    banner 'ACCEPTANCE FAILED: the commit is NOT cleared for production'
    exit 1
  fi
  if dirty; then
    say 'acceptance passed, but the working tree has uncommitted changes: no stamp written (commit first, then deploy to staging again).'
    exit 0
  fi
  printf '%s %s\n' "$(date -u +%FT%TZ)" "$log" >"$STATE/passed-$SHA"
  banner "ACCEPTANCE PASSED: stamp $STATE/passed-$SHA"
}

# ------------------------------------------------------------------------------------------------ prod
need_prod_checkout() {
  [ "$HERE" = "$MAIN" ] || die "prod deploys run from the main checkout ($MAIN), not from $HERE"
  [ -f "$ENV_FILE" ] || die "$ENV_FILE not found"
}

APP_IMAGE=agent-radio-app

service_hash_changed() { # <service>: 0 when compose would recreate it (config hash differs from the running container; a missing container counts)
  local svc=$1 want have cid
  want=$(dc config --hash "$svc" 2>/dev/null | awk -v s="$svc" '$1 == s { print $2 }')
  cid=$(dc ps -aq "$svc" 2>/dev/null | head -n 1)
  [ -n "$cid" ] || return 0
  have=$(docker inspect -f '{{index .Config.Labels "com.docker.compose.config-hash"}}' "$cid" 2>/dev/null || true)
  [ "$want" != "$have" ]
}

file_hash() { sha256sum "$1" | cut -d' ' -f1; }
state_value() { sed -n "s/^$1=//p" "$STATE/prod-state" 2>/dev/null | tail -n 1; }

deploy_prod() {
  need_prod_checkout
  local allow=0 smoke=0 dry=0 a
  for a in "$@"; do
    case $a in
      --allow-listener-drop) allow=1 ;;
      --smoke-say) smoke=1 ;;
      --dry-run) dry=1 ;;
      *) die "unknown option: $a" ;;
    esac
  done
  # ---- gate
  dirty && die 'the working tree is not clean'
  git -C "$HERE" fetch -q origin main || die 'git fetch origin main failed'
  [ "$SHA" = "$(git -C "$HERE" rev-parse origin/main)" ] || die "HEAD ($SHA) is not origin/main: merge and pull first"
  [ -f "$STATE/passed-$SHA" ] || die "no staging stamp for $SHA: run scripts/deploy.sh staging on this commit first"

  banner "PRODUCTION  $(git -C "$HERE" rev-parse --short HEAD)"
  dc config --quiet
  # ---- plan: which services restart
  local drop=() reload_front=0 svc
  for svc in icecast front liquidsoap; do
    service_hash_changed "$svc" && drop+=("$svc")
  done
  local liq_now caddy_now
  liq_now=$(file_hash "$HERE/liquidsoap/radio.liq")
  caddy_now=$(file_hash "$HERE/deploy/Caddyfile")
  if [ "$liq_now" != "$(state_value liquidsoap)" ]; then
    case " ${drop[*]:-} " in *" liquidsoap "*) ;; *) drop+=(liquidsoap) ;; esac
  fi
  if [ "$caddy_now" != "$(state_value caddyfile)" ]; then reload_front=1; fi
  say "plan:"
  say "  app          rebuild + recreate (no listener impact when the front is in place)"
  if [ ${#drop[@]} -gt 0 ]; then
    say "  ${drop[*]}   RESTART: THE STREAM IS CUT ONCE (players reconnect by themselves, held messages wait up to 3 minutes)"
  fi
  [ $reload_front = 1 ] && [ ${#drop[@]} -eq 0 ] && say "  front        Caddyfile changed: graceful reload (streams stay up)"
  if [ ${#drop[@]} -gt 0 ]; then
    banner "WARNING: ${drop[*]} will restart and DROP THE LISTENERS"
    [ $allow = 1 ] || die 'refusing: add --allow-listener-drop if this is intended (see README "Deploy without dropping listeners")'
  fi
  [ $dry = 1 ] && { say 'dry run: nothing changed.'; exit 0; }

  # ---- backup, keep the previous image
  (cd "$HERE" && COMPOSE_PROJECT_NAME=$PROJECT "$HERE/scripts/backup.sh")
  if docker image inspect "$APP_IMAGE:latest" >/dev/null 2>&1; then
    docker tag "$APP_IMAGE:latest" "$APP_IMAGE:previous"
    say "previous app image kept as $APP_IMAGE:previous"
  fi

  # ---- apply: services that carry the stream first, then the app, then the front (the front takes the port the app used to publish)
  dc build app
  local d
  for d in "${drop[@]:-}"; do
    [ -n "$d" ] && [ "$d" != front ] && dc up -d --no-deps --force-recreate "$d"
  done
  dc up -d --no-deps app
  if [[ " ${drop[*]:-} " == *" front "* ]]; then
    dc up -d --no-deps --force-recreate front
  else
    dc up -d --no-deps front
    if [ $reload_front = 1 ]; then
      dc exec -T front caddy validate --config /etc/caddy/Caddyfile >/dev/null
      dc exec -T front caddy reload --config /etc/caddy/Caddyfile
    fi
  fi
  wait_healthy
  # record what is running now, even if a smoke check fails below (otherwise the next deploy sees phantom config changes)
  printf 'sha=%s\nliquidsoap=%s\ncaddyfile=%s\n' "$SHA" "$liq_now" "$caddy_now" >"$STATE/prod-state"

  # ---- smoke
  local url
  url=$(stream_url)
  if [ -n "$url" ]; then
    python3 "$HERE/scripts/stream-probe.py" "$url" --secs 5 --min-bytes 20000 || die 'smoke: the stream is not healthy: roll back with scripts/deploy.sh rollback'
  else
    say 'smoke: no station yet, the stream read is skipped'
  fi
  if [ $smoke = 1 ]; then
    local said
    said=$("$HERE/client/agent-radio" say --wait 'Перевірка після оновлення.' 2>&1 || true)
    printf '%s\n' "$said" >&2
    if printf '%s' "$said" | grep -q 'skipped'; then
      say 'smoke: nobody is listening (the deploy itself may have cut the listeners), the test message was skipped'
    else
      printf '%s' "$said" | grep -q '^agent-radio: played' || die 'smoke: the test message was not played'
    fi
  fi
  banner "PRODUCTION DEPLOYED $SHA"
  say "Rollback:  scripts/deploy.sh rollback   (restores $APP_IMAGE:previous; the database migrations are additive, the old app runs on the new database)"
  say "Database backup: see the 'backup:' line above (./backups)."
}

rollback_prod() {
  need_prod_checkout
  docker image inspect "$APP_IMAGE:previous" >/dev/null 2>&1 || die "no $APP_IMAGE:previous image"
  banner 'ROLLBACK of the production app'
  docker tag "$APP_IMAGE:latest" "$APP_IMAGE:rolled-back" 2>/dev/null || true
  docker tag "$APP_IMAGE:previous" "$APP_IMAGE:latest"
  dc up -d --no-build --no-deps --force-recreate app
  wait_healthy
  say "rolled back. The replaced image is kept as $APP_IMAGE:rolled-back. Fix forward, then deploy again."
}

case "$MODE" in
  staging) deploy_staging ;;
  prod) deploy_prod "$@" ;;
  rollback) rollback_prod ;;
esac
